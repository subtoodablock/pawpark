// Breed data (docs/07-art-direction.md §5). Pure data; dogSprite.ts turns it into pixels.
// Chibi proportions: huge round head, bean-shaped chubby body, short stubby legs.
// Units are "dog units" (about 0.9 css px each); the body is ~17 units tall, the head ~19 across.
export type EarKind = 'floppy' | 'long' | 'pointy' | 'big' | 'small' | 'rose' | 'puff';
export type TailKind = 'plume' | 'curl' | 'whip' | 'stub' | 'pom' | 'otter' | 'pug' | 'fluffcurl';
export type FurKind = 'smooth' | 'fluffy' | 'curly' | 'glossy';

export type Mark =
  | { k: 'e'; x: number; y: number; rx: number; ry: number; rot?: number; col: string }
  | { k: 'spots'; n: number; rMin: number; rMax: number; col: string; seed: number; rx: number; ry: number; ox?: number; oy?: number };

export interface Breed {
  id: string;
  name: string;
  seed: number;
  base: string;
  base2: string;
  earCol: string;
  tailCol: string;
  snoutCol: string;
  /** paw tip colour (null: a slightly lighter base) */
  sockCol: string | null;
  nose: string;
  /** iris colour (pupil is always dark) */
  iris: string;
  ear: EarKind;
  tail: TailKind;
  fur: FurKind;
  /** which part of the body silhouette gets soft scalloped tufts */
  fluff: 'none' | 'rear' | 'all' | 'chest';
  fluffSize: number;
  /** soft feathering on ears + tail */
  feather: boolean;
  /** distance between hip and shoulder centres */
  bodyL: number;
  /** body diameter */
  bodyH: number;
  /** visible leg length */
  legH: number;
  legW: number;
  headR: number;
  /** extra snout length */
  snoutL: number;
  size: number;
  eye: number;
  /** rosy cheek strength 0..1 */
  blush: number;
  /** body-local marks (origin = body middle, x along the spine) */
  body: Mark[];
  /** head-local marks (origin = head centre, +x toward the nose, y down) */
  head: Mark[];
}

