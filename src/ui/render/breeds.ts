// Breed data (docs/07-art-direction.md §5). Pure data; dogSprite.ts turns it into pixels.
export type EarKind = 'floppy' | 'long' | 'pointy' | 'big' | 'small' | 'rose' | 'puff';
export type TailKind = 'plume' | 'curl' | 'whip' | 'stub' | 'pom' | 'otter' | 'pug' | 'fluffcurl';
export type FurKind = 'smooth' | 'fluffy' | 'curly' | 'glossy';

export type Mark =
  | { k: 'e'; x: number; y: number; rx: number; ry: number; rot?: number; col: string }
  | { k: 'spots'; n: number; rMin: number; rMax: number; col: string; seed: number; rx: number; ry: number };

export interface Breed {
  id: string;
  name: string;
  seed: number;
  base: string;
  base2: string;
  earCol: string;
  tailCol: string;
  snoutCol: string;
  sockCol: string | null;
  nose: string;
  ear: EarKind;
  tail: TailKind;
  fur: FurKind;
  /** which part of the body silhouette gets scalloped tufts */
  fluff: 'none' | 'rear' | 'all' | 'chest';
  fluffSize: number;
  bodyL: number;
  bodyH: number;
  legH: number;
  legW: number;
  headR: number;
  snoutL: number;
  size: number;
  eye: number;
  /** body-local marks (origin = body middle, x along the spine) */
  body: Mark[];
  /** head-local marks (origin = head centre, +x toward the nose) */
  head: Mark[];
}

